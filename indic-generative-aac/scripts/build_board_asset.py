"""Generate the public vocabulary asset from the backend registry; --check verifies parity."""
from pathlib import Path
import json,sys
root=Path(__file__).resolve().parents[1]
board=json.loads((root/'backend/board_concepts.json').read_text())['concepts']
text='// Generated by scripts/build_board_asset.py; edit backend/board_concepts.json.\nwindow.AAC_CONCEPTS = '+json.dumps(board,ensure_ascii=False,indent=2)+';\n'
target=root/'frontend/board-registry.js'
if '--check' in sys.argv:
 if not target.exists() or target.read_text()!=text: raise SystemExit('Board asset differs from registry; regenerate it.')
 print('Registry parity:',len(board),'concepts')
else:target.write_text(text)
