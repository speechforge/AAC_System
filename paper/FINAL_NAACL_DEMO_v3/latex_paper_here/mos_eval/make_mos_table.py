#!/usr/bin/env python3
"""Aggregate mos_scores.csv into generated/tab_mos.tex (appendix table) and generated/mos.tex (macros used in the text)."""
import pathlib
import pandas as pd

HERE = pathlib.Path(__file__).resolve().parent
GEN = HERE.parent / "latex_source_v3/generated"
d = pd.read_csv(HERE / "mos_scores.csv", keep_default_na=False)


def ms(g, col, sd=True):
    return f"{g[col].mean():.2f}" + (f" ({g[col].std():.2f})" if sd and len(g) > 1 else "")


def pair(g, sd=True):
    return f"{ms(g, 'utmos', sd)} / {ms(g, 'nisqa_mos', sd)}"


tone = d[d.group == "placeholder"]
ref = d[d.group == "reference"]
ref_en, ref_mr = ref[ref.lang == "en"], ref[ref.lang == "mr"]
ref_def = ref[ref.id == "PAN_F_HAPPY_00001"]
st = d[d.group == "standin"]
n = {k: int((st.lang == k).sum()) for k in ("en", "hi", "gu", "mr")}
assert len(tone) == 1 and len(ref) == 8 and len(ref_def) == 1 and sum(n.values()) == 175

def sdp(g, col):
    return f"{g[col].mean():.2f} ({g[col].std():.2f})"


LANGS = (("English", "en"), ("Hindi", "hi"), ("Gujarati", "gu"), ("Marathi", "mr"))
cols = [("Tone", tone), ("English", ref_en), ("Marathi", ref_mr), ("Punjabi", ref_def)] + [(k, st[st.lang == c]) for k, c in LANGS]
fig = d[d.group == "indicf5"]                                   # empty until synth_indicf5.py has run with the gated weights
has_f5 = len(fig) > 0
if has_f5:
    cols += [(k, fig[fig.lang == c]) for k, c in LANGS]
sd_from = 4
u = [f"{g.utmos.mean():.2f}" for _, g in cols[:sd_from]] + [sdp(g, "utmos") for _, g in cols[sd_from:]]
nq = [f"{g.nisqa_mos.mean():.2f}" for _, g in cols[:sd_from]] + [sdp(g, "nisqa_mos") for _, g in cols[sd_from:]]
head2 = " & ".join([""] + [r"\lang{" + k + "} (" + str(len(g)) + ")" for k, g in cols] + ([] if has_f5 else [r"\indicf{} (0)"]))
last = "" if has_f5 else " & not run"
spec = "@{}l c ccc cccc " + ("cccc" if has_f5 else "c") + "@{}"
group_hdr = (r"\multicolumn{4}{c}{\indicf{}, deployed voice}" if has_f5 else "Deployed voice")
tab = r"""\begin{table*}[!t]
\centering\footnotesize
\setlength{\tabcolsep}{3.4pt}\renewcommand{\arraystretch}{1.1}
\begin{tabular}{""" + spec + r"""}
\toprule
\rowcolor{headtint}
 & Evaluated build & \multicolumn{3}{c}{Human voice prompts} & \multicolumn{4}{c}{Stand-in voice, deployed sentences} & """ + group_hdr + r""" \\
\rowcolor{headtint}
""" + head2 + r""" \\
\midrule
\utmos{} & \bad{""" + u[0] + "} & " + " & ".join(u[1:]) + last + r""" \\
\rowcolor{rowtint}\nisqa{} & \bad{""" + nq[0] + "} & " + " & ".join(nq[1:]) + last + r""" \\
\bottomrule
\end{tabular}
\caption{Predicted speech quality (1--5, higher is better; mean, and standard deviation for the synthesized voices; clips in the header). \emph{Tone}: the evaluated build's placeholder. Human prompts: clips that \indicf{} would imitate (Punjabi: the default for all languages). Stand-in voices: open \mmstts{} models reading the deployed sentences, not \indicf{}, whose weights are gated. Both predictors are trained on English ratings (indicative only).}
\label{tab:mos}
\end{table*}
"""
(GEN / "tab_mos.tex").write_text(tab, encoding="utf-8")


def lo_hi(vals):
    return f"{min(vals):.1f}", f"{max(vals):.1f}"


by = st.groupby("lang")[["utmos", "nisqa_mos"]].mean()
su = lo_hi(by.utmos); sn = lo_hi(by.nisqa_mos); ru = lo_hi(ref.utmos)
mac = {
    "MosToneU": f"{tone.utmos.iloc[0]:.1f}", "MosToneN": f"{tone.nisqa_mos.iloc[0]:.1f}",
    "MosRefULo": ru[0], "MosRefUHi": ru[1],
    "MosStandULo": su[0], "MosStandUHi": su[1], "MosStandNLo": sn[0], "MosStandNHi": sn[1],
    "MosNStand": str(len(st)), "MosNRef": str(len(ref)),
    "MosCorr": f"{st.utmos.corr(st.nisqa_mos):.2f}",
}
(GEN / "mos.tex").write_text("% AUTO-GENERATED by mos_eval/make_mos_table.py from mos_eval/mos_scores.csv\n" + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in mac.items()), encoding="utf-8")
print(tab); print(mac)
